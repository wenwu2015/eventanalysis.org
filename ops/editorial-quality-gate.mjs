#!/usr/bin/env node
import { readFile, readdir } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const publicRoot = resolve(root, "dist/client");
const publicExtensions = new Set([".html", ".xml", ".txt"]);
const blockedSignals = [
  /\b(?:AI|ChatGPT|OpenAI)\b/,
  /artificial intelligence|inteligencia artificial|inteligência artificial|intelligence artificielle|intelligenza artificiale/i,
  /künstliche intelligenz|人工智能|人工知能|인공지능|искусственн\w* интеллект/i,
  /\bKI\b/,
  /штучн\w* інтелект|الذكاء الاصطناعي|هوش مصنوعی|yapay zek[âa]|sztuczna inteligencja|kecerdasan buatan/i,
  /generated by|machine[- ]generated|as a language model|lorem ipsum/i,
  /\b(?:TODO|TBD)\b/,
  /in conclusion|it(?:'|’)s important to note|delve into|a testament to|rich tapestry/i,
  /综上所述|值得注意的是|不可否认的是|在当今\S{0,8}(?:时代|世界)|赋能|无疑是/i,
];

async function publicFiles(directory) {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) files.push(...await publicFiles(path));
    else if (publicExtensions.has(entry.name.slice(entry.name.lastIndexOf(".")))) files.push(path);
  }
  return files;
}

const failures = [];

for (const path of await publicFiles(publicRoot)) {
  const content = await readFile(path, "utf8");
  for (const pattern of blockedSignals) {
    const match = content.match(pattern);
    if (match) failures.push(`${path.slice(root.length + 1)}: blocked public wording ${JSON.stringify(match[0])}`);
  }
}

if (failures.length) {
  throw new Error(`Editorial quality gate failed:\n${failures.join("\n")}`);
}

console.log("Editorial quality gate passed: no automation attribution, placeholders or stock filler in public output.");
